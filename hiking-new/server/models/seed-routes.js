function sampleFields(track) {
  return {
    distance: track.stats.distance,
    geojson: JSON.stringify(track.geojson),
    ascentM: track.stats.ascentM,
    descentM: track.stats.descentM,
    minElevation: track.stats.minElevation,
    maxElevation: track.stats.maxElevation,
    pointCount: track.stats.pointCount,
    isSample: true,
  };
}

